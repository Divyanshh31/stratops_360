    private static final Logger log = LoggerFactory.getLogger(DataInitializer.class);

    private final KpiMetricRepository kpiRepository;
    private final KpiHistorySnapshotRepository historyRepository;
    private final DecisionInitiativeRepository initiativeRepository;
    private final CreditRuleEvaluationRepository evaluationRepository;
    private final RuleThresholdConfigRepository thresholdRepository;
    private final SavedScenarioRepository scenarioRepository;
    private final ExpertSystemProperties expertProperties;

    public DataInitializer(KpiMetricRepository kpiRepository,
                           KpiHistorySnapshotRepository historyRepository,
                           DecisionInitiativeRepository initiativeRepository,
                           CreditRuleEvaluationRepository evaluationRepository,
                           RuleThresholdConfigRepository thresholdRepository,
                           SavedScenarioRepository scenarioRepository,
                           ExpertSystemProperties expertProperties) {
        this.kpiRepository = kpiRepository;
        this.historyRepository = historyRepository;
        this.initiativeRepository = initiativeRepository;
        this.evaluationRepository = evaluationRepository;
        this.thresholdRepository = thresholdRepository;
        this.scenarioRepository = scenarioRepository;
        this.expertProperties = expertProperties;
    }

    @Override
    public void run(String... args) {
        initThresholds();
        initKpis();
        initDecisions();
        initCreditEvaluations();
        initSavedScenarios();
        log.info("StratOps 360 Enterprise Seed Data successfully initialized.");
    }

    private void initThresholds() {
        if (thresholdRepository.count() == 0) {
            RuleThresholdConfig config = new RuleThresholdConfig(
                    expertProperties.getMinIncome(),
                    expertProperties.getMaxCarRatio(),
                    expertProperties.getMaxMortgageRatio(),
                    expertProperties.getMinTenureYears(),
                    expertProperties.getMaxOtherDebtRatio(),
                    expertProperties.getTier1Limit(),
                    expertProperties.getTier2Limit(),
                    "System Defaults (Slide 9)"
            );
            thresholdRepository.save(config);
        }
    }

