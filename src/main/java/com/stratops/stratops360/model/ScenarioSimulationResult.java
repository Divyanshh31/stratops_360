package com.stratops.stratops360.model;

import java.util.ArrayList;
import java.util.List;

public class ScenarioSimulationResult {

    private String scenarioName;
    private ScenarioSimulationRequest request;

    // Financial: Operating Margin (%)
    private double baseOperatingMargin;
    private double simulatedOperatingMargin;

    // Financial: Projected Net Profit ($M)
    private double baseNetProfit;
    private double simulatedNetProfit;

    // Customer: Retention Rate (%)
    private double baseCustomerRetention;
    private double simulatedCustomerRetention;

    // Customer: Net Promoter Score (NPS)
    private double baseNps;
    private double simulatedNps;

    // Internal Process: Order Fulfillment Cycle Time (Days)
    private double baseCycleTime;
    private double simulatedCycleTime;

    // Internal Process: Defect Rate (%)
    private double baseDefectRate;
    private double simulatedDefectRate;

    // Learning and Growth: Employee Retention (%)
    private double baseEmployeeRetention;
    private double simulatedEmployeeRetention;

    // Recommendations generated by DSS engine
    private List<String> strategicInsights = new ArrayList<>();
    private String riskLevel; // LOW, MODERATE, HIGH

    public ScenarioSimulationResult() {
    }

    public void addInsight(String insight) {
        strategicInsights.add(insight);
    }

    // Getters and Setters
    public String getScenarioName() {
        return scenarioName;
    }

    public void setScenarioName(String scenarioName) {
        this.scenarioName = scenarioName;
    }

    public ScenarioSimulationRequest getRequest() {
        return request;
    }

    public void setRequest(ScenarioSimulationRequest request) {
        this.request = request;
    }

    public double getBaseOperatingMargin() {
        return baseOperatingMargin;
    }

    public void setBaseOperatingMargin(double baseOperatingMargin) {
        this.baseOperatingMargin = baseOperatingMargin;
    }

    public double getSimulatedOperatingMargin() {
        return simulatedOperatingMargin;
    }

    public void setSimulatedOperatingMargin(double simulatedOperatingMargin) {
        this.simulatedOperatingMargin = simulatedOperatingMargin;
    }

    public double getBaseNetProfit() {
        return baseNetProfit;
    }

    public void setBaseNetProfit(double baseNetProfit) {
        this.baseNetProfit = baseNetProfit;
    }

    public double getSimulatedNetProfit() {
        return simulatedNetProfit;
    }

    public void setSimulatedNetProfit(double simulatedNetProfit) {
        this.simulatedNetProfit = simulatedNetProfit;
    }

    public double getBaseCustomerRetention() {
        return baseCustomerRetention;
    }

    public void setBaseCustomerRetention(double baseCustomerRetention) {
        this.baseCustomerRetention = baseCustomerRetention;
    }

    public double getSimulatedCustomerRetention() {
        return simulatedCustomerRetention;
    }

    public void setSimulatedCustomerRetention(double simulatedCustomerRetention) {
        this.simulatedCustomerRetention = simulatedCustomerRetention;
    }

    public double getBaseNps() {
        return baseNps;
    }

    public void setBaseNps(double baseNps) {
        this.baseNps = baseNps;
    }

    public double getSimulatedNps() {
        return simulatedNps;
    }

    public void setSimulatedNps(double simulatedNps) {
        this.simulatedNps = simulatedNps;
    }

    public double getBaseCycleTime() {
        return baseCycleTime;
    }

    public void setBaseCycleTime(double baseCycleTime) {
        this.baseCycleTime = baseCycleTime;
    }

    public double getSimulatedCycleTime() {
        return simulatedCycleTime;
    }

    public void setSimulatedCycleTime(double simulatedCycleTime) {
        this.simulatedCycleTime = simulatedCycleTime;
    }

    public double getBaseDefectRate() {
        return baseDefectRate;
    }

    public void setBaseDefectRate(double baseDefectRate) {
        this.baseDefectRate = baseDefectRate;
    }

    public double getSimulatedDefectRate() {
        return simulatedDefectRate;
    }

    public void setSimulatedDefectRate(double simulatedDefectRate) {
        this.simulatedDefectRate = simulatedDefectRate;
    }

    public double getBaseEmployeeRetention() {
        return baseEmployeeRetention;
    }

    public void setBaseEmployeeRetention(double baseEmployeeRetention) {
        this.baseEmployeeRetention = baseEmployeeRetention;
    }

    public double getSimulatedEmployeeRetention() {
        return simulatedEmployeeRetention;
    }

    public void setSimulatedEmployeeRetention(double simulatedEmployeeRetention) {
        this.simulatedEmployeeRetention = simulatedEmployeeRetention;
    }

    public List<String> getStrategicInsights() {
        return strategicInsights;
    }

    public void setStrategicInsights(List<String> strategicInsights) {
        this.strategicInsights = strategicInsights;
    }

    public String getRiskLevel() {
        return riskLevel;
    }

    public void setRiskLevel(String riskLevel) {
        this.riskLevel = riskLevel;
    }
}
